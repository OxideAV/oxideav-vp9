//! [`oxideav_vp9::decode_intra_frame`] — VP9 spec v0.7 §6.2 → §6.3 →
//! §6.4 → §8.5/§8.6/§8.7 → §8.8 → §8.10 composition.
//!
//! Three fixtures from the clean-room corpus staged under
//! `docs/video/vp9/fixtures/` are embedded verbatim (frame payload +
//! expected planar output) so the pins run in standalone CI where the
//! docs tree is not checked out:
//!
//! * `tiny-i-only-16x16` — minimal 16x16 keyframe, one superblock
//!   split to 8x8 leaves, flat content, `loop_filter_level = 0`.
//! * `lossless-i-only` — 64x64 lossless keyframe (`base_q_idx = 0`):
//!   forced `TX_4X4` + the §8.7.1.10 inverse WHT path on structured
//!   content.
//! * `q-low` — 64x64 keyframe at the low-quantizer extreme
//!   (`base_q_idx = 4`): dense coefficient streams through the §8.7
//!   inverse DCT/ADST paths.
//!
//! Each `expected.yuv` is byte-for-byte ground truth produced by an
//! independent decoder run over the same bitstream (see the per-
//! fixture `notes.md` in the docs corpus). A fourth test sweeps every
//! intra-leading fixture in the corpus when the docs tree is present
//! (workspace checkouts), comparing the leading keyframe byte-exactly.

use oxideav_vp9::{decode_intra_frame, decode_vp9, Error};

fn from_hex_lines(lines: &[&str]) -> Vec<u8> {
    let mut out = Vec::new();
    for line in lines {
        assert!(line.len() % 2 == 0);
        for i in (0..line.len()).step_by(2) {
            out.push(u8::from_str_radix(&line[i..i + 2], 16).expect("hex"));
        }
    }
    out
}


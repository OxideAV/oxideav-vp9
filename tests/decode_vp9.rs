/// `tiny-i-only-16x16`: 16x16 keyframe decodes byte-exactly. The flat
/// content means every plane is a single value — but the pin compares
/// the staged `expected.yuv` verbatim rather than re-deriving that.
#[test]
fn tiny_16x16_keyframe_decodes_byte_exact() {
    let frame = from_hex_lines(TINY_FRAME);
    let expected = from_hex_lines(TINY_EXPECTED);
    let out = decode_vp9(&frame).expect("tiny keyframe decodes");
    assert_eq!(out.len(), 16 * 16 + 2 * 8 * 8);
    assert_eq!(out, expected);
}

/// `tiny-i-only-16x16` via [`decode_intra_frame`]: geometry metadata
/// matches the §6.2 header (16x16, profile 0 → 8-bit 4:2:0).
#[test]
fn tiny_16x16_keyframe_frame_metadata() {
    let frame = from_hex_lines(TINY_FRAME);
    let decoded = decode_intra_frame(&frame).expect("tiny keyframe decodes");
    assert_eq!(decoded.width, 16);
    assert_eq!(decoded.height, 16);
    assert_eq!(decoded.bit_depth, 8);
    assert!(decoded.subsampling_x);
    assert!(decoded.subsampling_y);
    assert_eq!(decoded.y.len(), 256);
    assert_eq!(decoded.u.len(), 64);
    assert_eq!(decoded.v.len(), 64);
}


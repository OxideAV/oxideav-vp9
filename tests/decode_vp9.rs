/// Truncating the tile payload of a valid frame surfaces a decode
/// error instead of panicking, for every truncation point.
#[test]
fn truncated_frame_errors_cleanly() {
    let frame = from_hex_lines(TINY_FRAME);
    for len in 0..frame.len() {
        assert!(
            decode_vp9(&frame[..len]).is_err(),
            "truncation at {len} must error"
        );
    }
}

/// A `show_existing_frame = 1` short frame (§6.2: frame_marker +
/// profile bits + show_existing_frame + frame_to_show_map_idx) needs
/// reference-buffer state and reports [`Error::Unsupported`].
#[test]
fn show_existing_frame_is_unsupported() {
    // Bits: frame_marker f(2) = 2, profile_low f(1) = 0,
    // profile_high f(1) = 0, show_existing_frame f(1) = 1,
    // frame_to_show_map_idx f(3) = 0 -> 0b1000_1000.
    assert_eq!(decode_vp9(&[0x88]), Err(Error::Unsupported));
}

/// Workspace-checkout sweep: when the docs corpus is reachable
/// (running inside the umbrella checkout), decode the leading
/// keyframe of every intra-leading fixture and compare byte-exactly
/// against the staged `expected.yuv` prefix. Standalone CI (no docs
/// tree) exercises the three embedded fixtures above instead.
#[test]
fn docs_corpus_intra_fixtures_decode_byte_exact() {
    let base = std::path::Path::new("../../docs/video/vp9/fixtures");
    if !base.is_dir() {
        eprintln!("docs corpus not present; embedded-fixture pins cover this configuration");
        return;
    }
    let fixtures = [
        "tiny-i-only-16x16",
        "lossless-i-only",
        "q-low",
        "q-high",
        "segments-aq-mode",
        "profile-0-yuv420-8bit",
        "profile-1-yuv444-8bit",
        "profile-2-yuv420-10bit",
        "profile-3-yuv444-10bit",
        "profile-3-yuv444-12bit",
        "bit-depth-10-rgb",
        "tile-cols-2",
        "frame-parallel-mode",
    ];
    for name in fixtures {
        let ivf = std::fs::read(base.join(name).join("input.ivf")).expect("input.ivf");
        let expected = std::fs::read(base.join(name).join("expected.yuv")).expect("expected.yuv");
        // IVF container: 32-byte file header, then per-frame 12-byte
        // headers whose first 4 bytes are the little-endian payload
        // size. Only the leading keyframe is decoded.
        let size = u32::from_le_bytes([ivf[32], ivf[33], ivf[34], ivf[35]]) as usize;
        let frame = &ivf[44..44 + size];
        let out = decode_vp9(frame).expect(name);
        // Multi-frame fixtures concatenate per-frame planar output;
        // compare the keyframe-sized prefix.
        assert!(
            out.len() <= expected.len(),
            "{name}: output longer than expected.yuv"
        );
        let diffs = out
            .iter()
            .zip(expected.iter())
            .filter(|(a, b)| a != b)
            .count();
        assert_eq!(diffs, 0, "{name}: {diffs} differing bytes");
    }
}
